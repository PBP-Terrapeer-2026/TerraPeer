from datetime import timedelta
from django.db import transaction
from django.utils import timezone
from .models import CareTask, Plant


@transaction.atomic
def complete_task(task_id, owner):
    task = (
        CareTask.objects.select_for_update()
        .select_related("plant__garden")
        .get(pk=task_id, plant__garden__owner=owner)
    )
    if task.status == "Completed":
        return task, None, False
    # Conditional update adds a second guard against duplicate completion.
    changed = CareTask.objects.filter(pk=task.pk, status="Pending").update(
        status="Completed", completed_at=timezone.now()
    )
    if not changed:
        return task, None, False
    task.refresh_from_db()
    following = None
    active = Plant.objects.filter(pk=task.plant_id, status="Active").exists()
    if task.repeat_every and active:
        date = task.due_date + timedelta(days=task.repeat_every)
        following = CareTask.objects.create(
            plant=task.plant,
            title=task.title,
            action_type=task.action_type,
            due_date=date,
            repeat_every=task.repeat_every,
            instructions=task.instructions,
            previous=task,
        )
    return task, following, True


class UndoCompletionConflict(Exception):
    """Undo would discard a follow-up changed by the user."""


@transaction.atomic
def undo_completion(task_id, owner):
    task = (
        CareTask.objects.select_for_update()
        .select_related("plant__garden")
        .get(pk=task_id, plant__garden__owner=owner)
    )
    if task.status == "Pending":
        return task, False
    following = CareTask.objects.select_for_update().filter(previous=task).first()
    if following:
        # Delete only the pending reminder generated by this completion.
        expected_date = (
            task.due_date + timedelta(days=task.repeat_every)
            if task.repeat_every
            else None
        )
        copied_fields = (
            "plant_id",
            "title",
            "action_type",
            "instructions",
            "repeat_every",
        )
        unchanged = all(
            getattr(following, field) == getattr(task, field) for field in copied_fields
        )
        has_descendant = CareTask.objects.filter(previous=following).exists()
        if (
            following.status != "Pending"
            or following.due_date != expected_date
            or not unchanged
            or has_descendant
        ):
            raise UndoCompletionConflict(
                "Cannot undo: the next reminder has been changed or completed. "
                "Your later work has been kept."
            )
        following.delete()
    task.status = "Pending"
    task.completed_at = None
    task.save(update_fields=["status", "completed_at"])
    return task, True
